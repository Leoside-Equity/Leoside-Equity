/* Builds assets/js/land-mask.js from Natural Earth's 1:110m land outline.

   Run once, only when you want to regenerate the file:
     node scripts/make-land-mask.mjs path/to/land-110m.json

   Source: world-atlas@2.0.2 (land-110m.json), which is Natural Earth data in
   the public domain. The output is a 720 x 360 equirectangular bitmap (half a
   degree per cell), run length encoded and stored as base64, a few kilobytes.
   The globe on the home page looks each pixel's latitude and longitude up in
   it to decide whether that point is land or sea.

   Two things the rasteriser has to get right, both of which showed up as
   stray bands on the globe when it did not:

   - Coastlines that cross the 180 degree meridian (the far east of Russia,
     Fiji) jump from +180 to -180 between two points. Read literally that is
     an edge across the whole map. Each ring is unwrapped so consecutive
     points never differ by more than 180 degrees, and filled spans wrap
     round the map.
   - Antarctica's ring runs all the way round the globe rather than enclosing
     an area on the flat map, so it is closed along the south pole.

   Each ring is filled on its own and XORed into the bitmap, so holes (lakes
   carved out of land) cancel correctly and no ring can disturb another. */

import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/make-land-mask.mjs land-110m.json'); process.exit(1); }

const topo = JSON.parse(readFileSync(src, 'utf8'));
const { scale, translate } = topo.transform;

const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => {
    x += dx; y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

function ring(indexes) {
  const out = [];
  indexes.forEach((i, n) => {
    const pts = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
    pts.forEach((p, k) => { if (n === 0 || k > 0) out.push(p); });
  });
  return out;
}

/* Consecutive points never more than 180 degrees apart. A ring that ends a
   full turn away from where it started goes round a pole; close it there. */
function unwrap(r) {
  const out = [[r[0][0], r[0][1]]];
  for (let i = 1; i < r.length; i++) {
    let lon = r[i][0];
    const prev = out[i - 1][0];
    while (lon - prev > 180) lon -= 360;
    while (lon - prev < -180) lon += 360;
    out.push([lon, r[i][1]]);
  }
  const turn = out[out.length - 1][0] - out[0][0];
  if (Math.abs(turn) > 180) {
    const meanLat = out.reduce((s, p) => s + p[1], 0) / out.length;
    const pole = meanLat < 0 ? -90 : 90;
    out.push([out[out.length - 1][0], pole], [out[0][0], pole], [out[0][0], out[0][1]]);
  }
  return out;
}

const rings = [];
const geoms = topo.objects.land.type === 'GeometryCollection' ? topo.objects.land.geometries : [topo.objects.land];
geoms.forEach((g) => {
  const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs;
  polys.forEach((poly) => poly.forEach((r) => rings.push(unwrap(ring(r)))));
});

const W = 720, H = 360;
const bits = new Uint8Array(W * H);

for (let j = 0; j < H; j++) {
  const lat = 90 - (j + 0.5) * (180 / H);
  rings.forEach((r) => {
    const xs = [];
    for (let k = 0; k < r.length - 1; k++) {
      const [x1, y1] = r[k], [x2, y2] = r[k + 1];
      if ((y1 <= lat && y2 > lat) || (y2 <= lat && y1 > lat)) {
        xs.push(x1 + (lat - y1) / (y2 - y1) * (x2 - x1));
      }
    }
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const a = Math.round((xs[k] + 180) / 360 * W);
      const b = Math.round((xs[k + 1] + 180) / 360 * W);
      for (let i = a; i < b; i++) {
        const col = ((i % W) + W) % W;
        bits[j * W + col] ^= 1;
      }
    }
  });
}

const bytes = [];
function varint(n) { while (n > 127) { bytes.push((n & 127) | 128); n >>>= 7; } bytes.push(n); }
for (let j = 0; j < H; j++) {
  let cur = 0, run = 0;
  const runs = [];
  for (let i = 0; i < W; i++) {
    const v = bits[j * W + i];
    if (v === cur) run++;
    else { runs.push(run); cur = v; run = 1; }
  }
  runs.push(run);
  varint(runs.length);
  runs.forEach(varint);
}

const b64 = Buffer.from(bytes).toString('base64');
const land = bits.reduce((a, b) => a + b, 0);
writeFileSync('assets/js/land-mask.js',
  '/* Natural Earth 1:110m land (public domain), 720x360, run length encoded.\n' +
  '   Generated by scripts/make-land-mask.mjs. Do not edit by hand. */\n' +
  'window.LS_LAND={w:' + W + ',h:' + H + ',d:"' + b64 + '"};\n');
console.log('rings', rings.length, 'land cells', land, 'of', W * H, '(' + (land / (W * H) * 100).toFixed(1) + '%)', 'bytes', b64.length);
